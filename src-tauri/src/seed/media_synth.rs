#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn synth_wav_is_riff_wave_with_payload() {
        let wav = synth_wav_tone(100, 8_000);
        assert!(
            wav.len() > 44,
            "expected non-trivial length for 100ms, got {}",
            wav.len()
        );
        assert_eq!(&wav[0..4], b"RIFF");
        assert_eq!(&wav[8..12], b"WAVE");
        // PCM data: 8000 * 0.1 * 2 bytes = 1600, plus 44 header ≈ 1644
        assert!(
            wav.len() >= 44 + 1600,
            "expected at least header+PCM for 100ms@8kHz, got {}",
            wav.len()
        );
    }

    #[test]
    fn synth_text_file_is_utf8_txt() {
        let (bytes, ext) = synth_text_file("meeting-notes");
        assert_eq!(ext, "txt");
        assert!(!bytes.is_empty());
        let s = std::str::from_utf8(&bytes).expect("utf-8");
        assert!(s.contains("meeting-notes"));
    }

    #[test]
    fn minimal_jpeg_has_soi_eoi() {
        let jpeg = minimal_jpeg_bytes();
        assert!(jpeg.len() >= 4);
        assert_eq!(&jpeg[0..2], &[0xFF, 0xD8], "SOI");
        assert_eq!(&jpeg[jpeg.len() - 2..], &[0xFF, 0xD9], "EOI");
    }

    /// Network test — run with `cargo test media_synth -- --ignored`.
    #[test]
    #[ignore]
    fn fetch_picsum_jpeg_downloads_jpeg() {
        let bytes = fetch_picsum_jpeg(42, 64, 64).expect("picsum download");
        assert!(bytes.len() > 100, "expected real image bytes");
        assert_eq!(&bytes[0..2], &[0xFF, 0xD8], "JPEG SOI");
    }
}
