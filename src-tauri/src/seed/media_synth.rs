//! Synthetic media bytes for demo seed (WAV, text, minimal JPEG) + Picsum fetch.

use std::f64::consts::PI;
use std::time::Duration;

/// Valid RIFF/WAVE PCM mono 16-bit little-endian sine tone (440 Hz).
pub fn synth_wav_tone(duration_ms: u32, sample_rate: u32) -> Vec<u8> {
    let sample_rate = sample_rate.max(1);
    let num_samples = ((sample_rate as u64).saturating_mul(duration_ms as u64) / 1000) as usize;
    let data_size = (num_samples * 2) as u32; // 16-bit mono
                                              // RIFF chunk size = "WAVE" + fmt(8+16) + data(8+data_size) = 36 + data_size
    let riff_size = 36u32.saturating_add(data_size);

    let mut out = Vec::with_capacity(44 + num_samples * 2);

    // RIFF header
    out.extend_from_slice(b"RIFF");
    out.extend_from_slice(&riff_size.to_le_bytes());
    out.extend_from_slice(b"WAVE");

    // fmt chunk (PCM mono 16-bit)
    out.extend_from_slice(b"fmt ");
    out.extend_from_slice(&16u32.to_le_bytes()); // chunk size
    out.extend_from_slice(&1u16.to_le_bytes()); // audio format = PCM
    out.extend_from_slice(&1u16.to_le_bytes()); // channels = mono
    out.extend_from_slice(&sample_rate.to_le_bytes());
    let byte_rate = sample_rate.saturating_mul(2); // sample_rate * channels * bits/8
    out.extend_from_slice(&byte_rate.to_le_bytes());
    out.extend_from_slice(&2u16.to_le_bytes()); // block align
    out.extend_from_slice(&16u16.to_le_bytes()); // bits per sample

    // data chunk
    out.extend_from_slice(b"data");
    out.extend_from_slice(&data_size.to_le_bytes());

    const FREQ_HZ: f64 = 440.0;
    const AMPLITUDE: f64 = 0.3;
    let sr = sample_rate as f64;
    for i in 0..num_samples {
        let t = i as f64 / sr;
        let sample = (AMPLITUDE * (2.0 * PI * FREQ_HZ * t).sin() * i16::MAX as f64) as i16;
        out.extend_from_slice(&sample.to_le_bytes());
    }

    out
}

/// Small UTF-8 demo note; returns `(bytes, extension without dot)` e.g. `"txt"`.
pub fn synth_text_file(name_hint: &str) -> (Vec<u8>, String) {
    let body = format!(
        "Memlore demo attachment\n\
         name: {name_hint}\n\
         This is a synthetic text file generated by the demo seed.\n"
    );
    (body.into_bytes(), "txt".to_string())
}

/// Download JPEG from Lorem Picsum. Follows redirects.
///
/// URL: `https://picsum.photos/seed/{seed}/{w}/{h}`
pub fn fetch_picsum_jpeg(seed: u32, w: u32, h: u32) -> Result<Vec<u8>, String> {
    let url = format!("https://picsum.photos/seed/{seed}/{w}/{h}");
    let client = reqwest::blocking::Client::builder()
        .redirect(reqwest::redirect::Policy::limited(10))
        .timeout(Duration::from_secs(30))
        .build()
        .map_err(|e| format!("picsum client: {e}"))?;

    let resp = client
        .get(&url)
        .send()
        .map_err(|e| format!("picsum request: {e}"))?;

    if !resp.status().is_success() {
        return Err(format!("picsum HTTP {}", resp.status()));
    }

    let bytes = resp.bytes().map_err(|e| format!("picsum body: {e}"))?;
    Ok(bytes.to_vec())
}

