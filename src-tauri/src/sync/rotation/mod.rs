//! Master-key rotation engine for the V2 keyring.
//!
//! # State machine
//!
//! ```text
//! enumerate → reencrypt → commit_local → enumerate_stragglers → publish_keyring → done
//!                                                                                ↘ aborted
//! ```
//!
//! Each state transition is a single DB write to `rotation_job.state`. On
//! startup, `resume_rotation_if_any` finds any in-progress job via
//! `find_active_rotation_job` and drives it forward from the recorded state.
//!
//! # Crash safety
//!
//! Before leaving the `enumerate` state both the old and the new master keys
//! are wrapped with the device password and persisted locally as
//! `rotation_master_old_wrapped_local` and `rotation_master_new_wrapped_local`.
//! This means crash-resume only requires the device password until
//! `publish_keyring` time — the 24-word mnemonic is only needed when writing
//! `_recovery.json`.
//!
//! # Security decisions
//!
//! **Device password at rotation start (Option A from the plan).**  Both
//! `revoke_device` and `rotate_master_key` prompt for the current password AND
//! the 24-word recovery phrase.  The password is needed to re-wrap
//! `master_key_new` into this device's **local** unlock material (the boot
//! file / settings `wrapped_encryption_key`, see `commit_local_inner`) and to
//! verify the caller via `verify_password_hash`; the phrase is needed to write
//! a fresh `_recovery.json`.  It is **not** used for any cloud wrap — cloud
//! device slots carry no key material at all (Phase 2 de-grind).  Without both
//! we would either lose the recovery property or be unable to re-key this
//! device locally.

