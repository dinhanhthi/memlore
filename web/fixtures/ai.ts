// ─── Usage summary ────────────────────────────────────────────────────────────

function sinceMs(period: UsagePeriod): number {
  const periods: Record<UsagePeriod, number> = {
    '24h': 1 * DAY,
    '7d': 7 * DAY,
    '30d': 30 * DAY,
    '90d': 90 * DAY,
    all: 365 * DAY * 3,
  }
  return now - (periods[period] ?? 30 * DAY)
}

function dailyPoints(period: UsagePeriod): AiUsageSummary['daily'] {
  const days =
    period === '24h' ? 1 : period === '7d' ? 7 : period === '30d' ? 30 : period === '90d' ? 90 : 180
  // Pseudo-random but stable pattern using day index
  const base = [
    8, 12, 5, 0, 18, 22, 15, 9, 6, 20, 28, 14, 7, 11, 24, 30, 16, 10, 4, 22, 19, 13, 8, 25, 31, 17,
    9, 21, 14, 6,
  ]
  const points: AiUsageSummary['daily'] = []
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(now - i * DAY)
    const date = d.toISOString().slice(0, 10)
    const calls = base[i % base.length] ?? 10
    points.push({
      date,
      calls,
      tokens_in: calls * 420,
      tokens_out: calls * 285,
    })
  }
  return points
}

